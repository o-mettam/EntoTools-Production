/* EntoTools shared theme — single source of truth for the brand palette and
 * dark-mode handling. Every page loads this, so the theme can only ever be
 * changed in one place.
 *
 * Load order in <head>:
 *
 *     <link rel="stylesheet" href="/tailwind.css">   (static build — tailwind.config.js reads PALETTE below)
 *     <script src="/theme.js?v=N"></script>
 *     <link rel="stylesheet" href="/theme.css">
 *
 * Tailwind is compiled at build time now (security assessment 2026-09, R4);
 * the PALETTE literal below is parsed by tailwind.config.js, so keep it a
 * plain object literal. If the Tailwind Play CDN is ever loaded again the
 * runtime config is still applied for it.
 *
 * Also hosts the site-wide event delegation (data-action / data-change /
 * data-input) that replaced inline onclick="…" handlers — see the bottom.
 *
 * This file is NOT generated by scripts/build-public.sh — edit it here, and
 * bump ?v=N in every template when you do (same convention as account.js).
 */
(function () {
    'use strict';

    // ── App version ──────────────────────────────────────────────
    // Single source of truth for the version shown in the Settings panel and
    // attached to feedback/bug reports. KEEP IN SYNC with the "version" field
    // in package.json.
    var APP_VERSION = '1.11.0';

    // ── Brand palette ────────────────────────────────────────────
    // Overrides Tailwind's default `lime` and `slate` ramps. Pages that miss
    // this config fall back to stock Tailwind colors and look off-brand, which
    // is exactly the drift this file exists to prevent.
    var PALETTE = {
        lime: {
            50: '#f5fadf', 100: '#ecf5bd', 200: '#dbec8e', 300: '#d0e672', 400: '#c4e055',
            500: '#b8d846', 600: '#abd037', 700: '#8aaa25', 800: '#6d881a', 900: '#4d6112', 950: '#3a4a0d',
        },
        slate: {
            50: '#eef1f6', 100: '#d8dee9', 200: '#bdc6d8', 300: '#9ca9c0', 400: '#7b8ba8',
            500: '#687794', 600: '#54637f', 700: '#3e4a64', 800: '#2a3348', 900: '#1a2030', 950: '#111828',
        },
    };

    // Only relevant if the Play CDN is loaded; the production build compiles
    // the same palette statically (tailwind.config.js).
    if (window.tailwind) {
        window.tailwind.config = { darkMode: 'class', theme: { extend: { colors: PALETTE } } };
    }

    // ── Theme preference ─────────────────────────────────────────
    var STORAGE_KEY = 'ento-theme';
    var LEGACY_KEY = 'firefly-theme';

    function stored() {
        var v = null;
        try {
            v = localStorage.getItem(STORAGE_KEY);
            if (v === null) {
                // One-time migration from the pre-rename key.
                v = localStorage.getItem(LEGACY_KEY);
                if (v !== null) {
                    localStorage.setItem(STORAGE_KEY, v);
                    localStorage.removeItem(LEGACY_KEY);
                }
            }
        } catch (e) { /* private mode / storage disabled */ }
        return v === 'dark' || v === 'light' ? v : null;
    }

    function prefersDark() {
        try { return window.matchMedia('(prefers-color-scheme: dark)').matches; }
        catch (e) { return false; }
    }

    // The theme actually in effect: an explicit choice, else the OS preference.
    function resolved() {
        return stored() || (prefersDark() ? 'dark' : 'light');
    }

    function apply(theme) {
        var root = document.documentElement;
        if (theme === 'dark') root.classList.add('dark');
        else root.classList.remove('dark');
    }

    // Applied immediately (this script is synchronous in <head>) so the page
    // never flashes light before the saved theme is honoured.
    apply(resolved());

    // ── Toggle control ───────────────────────────────────────────
    // Every page uses the same #theme-toggle / #theme-toggle-dot switch markup.
    function updateThemeToggleUI() {
        var isDark = document.documentElement.classList.contains('dark');
        var toggle = document.getElementById('theme-toggle');
        var dot = document.getElementById('theme-toggle-dot');
        if (toggle) {
            toggle.classList.toggle('bg-lime-600', isDark);
            toggle.classList.toggle('bg-slate-200', !isDark);
            toggle.setAttribute('aria-pressed', isDark ? 'true' : 'false');
        }
        if (dot) {
            dot.classList.toggle('translate-x-6', isDark);
            dot.classList.toggle('translate-x-1', !isDark);
        }
    }

    function set(theme) {
        theme = theme === 'dark' ? 'dark' : 'light';
        try { localStorage.setItem(STORAGE_KEY, theme); } catch (e) { /* ignore */ }
        apply(theme);
        updateThemeToggleUI();
        console.log('[EntoTheme] switched to', theme, 'mode');
    }

    function toggleTheme() {
        set(document.documentElement.classList.contains('dark') ? 'light' : 'dark');
    }

    // ── Version footer ───────────────────────────────────────────
    // Every page's Settings dropdown shares the id="settings-panel" markup —
    // append the version line there once instead of duplicating it per page.
    // Also appends the "Service Status" link (every page, except on /status
    // itself). account.js inserts its section ABOVE this link, so the panel
    // reads: page settings → account → Service Status → Version.
    function renderVersionInfo() {
        var panel = document.getElementById('settings-panel');
        if (!panel || document.getElementById('app-version-info')) return;
        if (!/^\/status\/?$/.test(location.pathname)) {
            var link = document.createElement('a');
            link.id = 'app-status-link';
            link.href = '/status';
            link.className = 'flex items-center gap-2 mt-3 pt-3 border-t border-slate-100 text-sm text-slate-700 hover:text-lime-700 transition';
            link.innerHTML = '<svg class="w-4 h-4 text-slate-500" fill="none" stroke="currentColor" stroke-width="2" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" d="M3 12h4l3-8 4 16 3-8h4"/></svg><span>Service Status</span>';
            panel.appendChild(link);
        }
        var footer = document.createElement('p');
        footer.id = 'app-version-info';
        footer.className = 'text-xs text-slate-400 mt-3 pt-3 border-t border-slate-100';
        footer.textContent = 'Version ' + APP_VERSION;
        panel.appendChild(footer);
    }

    // Exposed as globals because the switches are wired up with inline
    // onclick="toggleTheme()" across all pages.
    window.toggleTheme = toggleTheme;
    window.updateThemeToggleUI = updateThemeToggleUI;
    window.APP_VERSION = APP_VERSION;
    window.EntoTheme = {
        palette: PALETTE,
        version: APP_VERSION,
        get: stored,
        resolved: resolved,
        set: set,
        toggle: toggleTheme,
        syncToggleUI: updateThemeToggleUI,
    };

    // ── Event delegation (replaces inline onclick="…" handlers) ──
    // The CSP no longer allows inline script, which includes on*="…"
    // attributes. Markup declares intent instead and one listener per
    // event type dispatches to a GLOBAL function by name:
    //
    //     <button data-action="doSearch">                     → doSearch(event)
    //     <button data-action="removeRange" data-args="[3]">  → removeRange(3, event)
    //     <button data-action="deleteEntry" data-args="[2]" data-stop>  (also event.stopPropagation())
    //     <input  data-change="toggleDateMode">   <input data-input="debouncedRender">
    //
    // The event is always appended as the LAST argument, so handlers that
    // took (event) or (id) keep their existing signatures. Targets must be
    // reachable as window[name]: a `function` declaration or `window.x =`,
    // NOT a top-level const/let (those aren't window properties).
    function dispatch(attr, e) {
        var el = e.target && e.target.closest ? e.target.closest('[' + attr + ']') : null;
        if (!el) return;
        var name = el.getAttribute(attr);
        var fn = window[name];
        if (typeof fn !== 'function') { console.warn('[EntoTheme] no global handler named', name, 'for', attr); return; }
        if (el.hasAttribute('data-stop')) e.stopPropagation();
        var args = [];
        var raw = el.getAttribute('data-args');
        if (raw) {
            try { args = JSON.parse(raw); } catch (err) { console.warn('[EntoTheme] bad data-args on', name, raw); return; }
            if (!Array.isArray(args)) args = [args];
        }
        fn.apply(el, args.concat([e]));
    }
    document.addEventListener('click', function (e) { dispatch('data-action', e); });
    document.addEventListener('change', function (e) { dispatch('data-change', e); });
    document.addEventListener('input', function (e) { dispatch('data-input', e); });

    // Defaults for the shared nav — a page that defines its own
    // toggleMobileMenu() (function declaration, later in the document)
    // overrides this.
    window.toggleMobileMenu = function () {
        ['mobile-menu', 'hamburger-icon', 'close-icon'].forEach(function (id) {
            var el = document.getElementById(id);
            if (el) el.classList.toggle('hidden');
        });
    };
    window.goBack = function () { history.back(); };

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', function () {
            updateThemeToggleUI();
            renderVersionInfo();
        });
    } else {
        updateThemeToggleUI();
        renderVersionInfo();
    }

    // Follow the OS while the user has made no explicit choice.
    try {
        window.matchMedia('(prefers-color-scheme: dark)').addEventListener('change', function (ev) {
            if (stored()) return;
            apply(ev.matches ? 'dark' : 'light');
            updateThemeToggleUI();
        });
    } catch (e) { /* older browsers: no listener support */ }

    // Keep other open tabs in sync.
    window.addEventListener('storage', function (ev) {
        if (ev.key !== STORAGE_KEY) return;
        apply(resolved());
        updateThemeToggleUI();
    });
})();
